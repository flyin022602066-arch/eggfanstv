import assert from "node:assert/strict";
import { existsSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import react from "@vitejs/plugin-react";
import { chromium } from "playwright";
import { createServer } from "vite";

const webDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const output = resolve(webDir, "../.local/cache/eggfans-private-assets-e2e");
mkdirSync(output, { recursive: true });
const chromePath = "C:/Program Files/Google/Chrome/Application/chrome.exe";
const server = await createServer({ configFile: false, appType: "custom", root: webDir, plugins: [react()], resolve: { alias: { "@": resolve(webDir, "src") } }, define: { __APP_VERSION__: '"test"', __APP_CHANGELOG__: '""', __BEEFTV_HEAVY_MEDIA_ENABLED__: "true" }, server: { host: "127.0.0.1", port: 0 }, logLevel: "error" });
server.middlewares.use("/asset-test", async (_request, response) => {
    response.setHeader("Content-Type", "text/html");
    response.end(await server.transformIndexHtml("/asset-test", '<!doctype html><html><body><div id="root"></div><script type="module">import "/src/styles/globals.css";import {mountEggfansPrivateAssetsHarness} from "/test/fixtures/eggfans-private-assets-harness.tsx";mountEggfansPrivateAssetsHarness(document.getElementById("root"));</script></body></html>'));
});
let browser;
const operations = [];
const problems = [];
let syncs = 0;
try {
    await server.listen();
    const base = `http://127.0.0.1:${server.httpServer.address().port}`;
    browser = await chromium.launch({ headless: true, ...(existsSync(chromePath) ? { executablePath: chromePath } : {}) });
    const page = await browser.newPage({ viewport: { width: 1300, height: 1000 } });
    page.setDefaultTimeout(10000);
    page.on("pageerror", (error) => problems.push(error.message));
    await page.route("**/*", async (route) => {
        const request = route.request();
        const url = new URL(request.url());
        if (url.origin !== base) return route.abort();
        if (!url.pathname.startsWith("/api/")) return route.continue();
        const body = request.postDataJSON();
        let data = {};
        if (url.pathname === "/api/eggfans/private-avatar") {
            assert.equal(body.config.baseUrl, "https://api.eggfans.com");
            assert.equal(body.body.model, "doubao-seedance-2-0-260128");
            operations.push(body.operation);
            const group = { Id: "group-test", Name: "角色组", GroupType: "AIGC", Description: "描述" };
            const asset = { Id: "asset-test", Name: "角色图片", GroupId: group.Id, AssetType: "Image", Status: "Active" };
            if (body.operation === "list-groups") data = { Items: [group], Total: 1 };
            if (body.operation === "list-assets") data = { Items: [asset], Total: 1 };
            if (body.operation === "get-group") data = group;
            if (body.operation === "get-asset") data = asset;
            if (body.operation === "auth-session") data = { H5Link: "https://example.com/mock-auth", BytedToken: "mock-token" };
            if (body.operation === "group-from-token") data = { GroupId: group.Id };
        } else if (url.pathname.endsWith("/eggfans-private-asset")) {
            syncs++;
            assert.equal(body.config.baseUrl, "https://api.eggfans.com");
            data = { assetId: "asset-test", groupId: "group-test", uri: "asset://asset-test", status: "active" };
        } else if (url.pathname === "/api/eggfans/video-tasks/query") data = { items: [{ id: "task-test", model: "doubao-seedance-2-5-260628", status: "succeeded", content: { video_url: "https://example.com/video.mp4" } }] };
        return route.fulfill({ contentType: "application/json", body: JSON.stringify({ code: 0, data }) });
    });
    await page.goto(base + "/asset-test");
    await page.getByRole("button", { name: "私域人像库", exact: true }).click();
    await page.getByRole("dialog").waitFor();
    assert.equal(operations.length, 0, "Opening the modal must not request remote APIs");
    await page.getByRole("button", { name: "读取素材", exact: true }).click();
    await page.getByRole("cell", { name: "角色图片", exact: true }).waitFor();
    await page.getByRole("button", { name: "查询状态", exact: true }).click();
    await page.getByRole("button", { name: /改\s*名/ }).click();
    await page.getByLabel("私域素材名称").fill("新角色");
    await page.getByRole("button", { name: "保存名称", exact: true }).click();
    await page.getByLabel("选择本地参考资产").click();
    await page.getByText("测试角色 · image", { exact: true }).click();
    await page.getByRole("button", { name: "同步到私域库", exact: true }).click();
    await page.getByLabel("私域参考 URI").waitFor();
    await page.waitForFunction(() => document.querySelector('[aria-label="私域参考 URI"]').value === "asset://asset-test");
    assert.equal(syncs, 1);
    await page.getByRole("button", { name: "绑定本地资产", exact: true }).click();
    await page.getByRole("button", { name: /删\s*除/ }).click();
    await page.getByRole("button", { name: "OK", exact: true }).click();
    await page.getByRole("tab", { name: "素材组", exact: true }).click();
    await page.getByRole("button", { name: "读取素材组", exact: true }).click();
    await page.getByRole("button", { name: "详情 / 编辑", exact: true }).last().click();
    await page.getByLabel("素材组名称").fill("修改组");
    await page.getByRole("button", { name: "保存修改", exact: true }).click();
    await page.getByLabel("素材组名称").fill("新建组");
    await page.getByRole("button", { name: "创建素材组", exact: true }).click();
    await page.getByRole("button", { name: /删\s*除/ }).last().click();
    await page.getByRole("button", { name: "OK", exact: true }).click();
    await page.getByRole("tab", { name: "真人认证", exact: true }).click();
    await page.getByLabel("真人认证完成跳转地址").fill("https://example.com/complete");
    await page.getByRole("button", { name: "生成认证链接", exact: true }).click();
    await page.getByRole("link", { name: "打开真人认证页面", exact: true }).waitFor();
    await page.getByRole("button", { name: "认证完成，换取素材组", exact: true }).click();
    await page.getByRole("tab", { name: "视频任务", exact: true }).click();
    await page.getByRole("button", { name: "查询任务", exact: true }).click();
    await page.getByRole("cell", { name: "task-test", exact: true }).waitFor();
    await page.waitForTimeout(250);
    await page.screenshot({ path: resolve(output, "video-tasks.png"), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole("tab", { name: "参考素材", exact: true }).click();
    await page.waitForTimeout(250);
    const bounds = await page.getByRole("dialog").boundingBox();
    assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= 391, "Mobile dialog overflow");
    await page.screenshot({ path: resolve(output, "mobile-assets.png"), fullPage: true });
    for (const operation of ["list-assets", "get-asset", "update-asset", "delete-asset", "list-groups", "get-group", "update-group", "create-group", "delete-group", "auth-session", "group-from-token"]) assert.ok(operations.includes(operation), `Missing UI operation ${operation}`);
    assert.deepEqual(problems, []);
    console.log(JSON.stringify({ ok: true, mockedOperations: [...new Set(operations)], resourceSyncs: syncs, mobileDialogFits: true, externalRequestsAllowed: false }));
} finally {
    await browser?.close();
    await server.close();
}
